	function namuLink(name) {
		var key = String(name).replace(/\s*\([^)]*\)\s*/g, '').trim();
		return (
			'<a class="namu-link" target="_blank" rel="noopener noreferrer" href="https://namu.wiki/w/' +
			encodeURIComponent(key) +
			'">' + name + '</a>'
		);
	}

	/* '강아지상 연예인', ['박보검','아이유'] -> '강아지상 연예인: <a>박보검</a>, <a>아이유</a>' */
	function celebLinks(label, names) {
		return label + ': ' + names.map(namuLink).join(', ');
	}

