/* read_saju.js — 얼굴로 보는 사주팔자 (오행 관상)
 *
 * 생년월일로 보는 사주(Sec6)와는 다른 탭이다. 여기는 **얼굴 생김새**로 본다.
 *
 * 근거로 삼은 두 가지는 관상에서 실제로 쓰는 틀이다.
 *   ① 오행 얼굴형(五行 面相) — 목(긴 얼굴)·화(역삼각)·토(두툼)·금(각진)·수(둥근)
 *   ② 삼정(三停) — 이마 / 눈썹~코밑 / 코밑~턱 의 길이 비율을
 *      각각 초년·중년·말년에 대응시켜 본다
 * 점수는 얼굴 비율에서 바로 계산하므로 **같은 얼굴이면 늘 같은 결과**가 나온다.
 *
 * 기준값(MID)은 실제 얼굴 사진을 재서 중앙값으로 맞췄다. 안 그러면 다섯 중 하나로만 쏠린다.
 */
(function () {
	'use strict';

	/* 실제 얼굴 사진에서 잰 중앙값(MID)과 퍼짐 정도(SPAN).
	 * SPAN 은 상위 20%~하위 20% 폭의 절반이다 — 이만큼 벗어나면 "꽤 그런 편"이 된다.
	 * ⚠ 이 값을 눈대중으로 넣으면 다섯 중 하나로만 쏠린다. 처음에 그렇게 했다가
	 *   전부 '토'가 나왔다. 반드시 실측으로 잡을 것.
	 * (2026-09-08, 사진 80장. 정면만 골라 재면 실제 사용자 사진과 어긋나서, 고개가
	 *  조금 돌아간 것까지 전부 넣어 쟀다.) */
	var MID = {
		ratio: 1.222,      // 얼굴 세로/가로
		foreheadW: 0.880,  // 이마 폭 / 광대 폭
		jawW: 0.804,       // 턱 폭 / 광대 폭
		chinW: 0.188,      // 턱끝 폭 / 광대 폭
		jawAngle: 139.9,   // 하악각(도). 작을수록 각진 턱
		lipThick: 0.122
	};
	var SPAN = {
		ratio: 0.155, foreheadW: 0.027, jawW: 0.030,
		chinW: 0.018, jawAngle: 5.4, lipThick: 0.027
	};

	var 오행 = {
		목: {
			name: '목(木)', title: '나무를 닮은 얼굴', tag: '자라나는 상',
			기질: '위로 뻗는 기운입니다. 새로 시작하고, 배우고, 계획을 세우는 데 강합니다. ' +
				'가만히 있는 걸 못 견디는 대신, 한번 방향을 잡으면 꾸준히 밀고 갑니다. ' +
				'다만 마음이 급해서 뿌리를 덜 내린 채 가지부터 뻗을 때가 있습니다.',
			일: '기획·교육·연구처럼 없던 걸 세우는 일이 맞습니다. 반복만 하는 자리에 오래 두면 시듭니다.',
			대인: '먼저 다가가기보다 상대가 다가오게 만드는 쪽입니다. 사람을 가려 사귀는 편이라 폭은 좁아도 깊습니다.'
		},
		화: {
			name: '화(火)', title: '불을 닮은 얼굴', tag: '타오르는 상',
			기질: '드러나는 기운입니다. 표정이 빠르고 반응이 좋아 어디 가든 눈에 띕니다. ' +
				'좋고 싫음이 분명해서 감추는 걸 잘 못합니다. ' +
				'불은 잘 붙지만 오래 못 갑니다. 지치기 전에 쉬는 법을 배우는 게 평생 숙제입니다.',
			일: '사람 앞에 서는 일, 말하고 보여주는 일이 맞습니다. 영업·방송·강의·디자인 쪽입니다.',
			대인: '처음 만난 사람과도 금방 친해집니다. 대신 식는 것도 빨라서, 오래 가는 인연을 일부러 챙겨야 합니다.'
		},
		토: {
			name: '토(土)', title: '흙을 닮은 얼굴', tag: '사람이 모이는 상',
			기질: '품는 기운입니다. 서두르지 않고, 남의 말을 끝까지 듣습니다. ' +
				'그래서 사람이 모입니다. 큰소리 내지 않아도 자리가 무겁습니다. ' +
				'다만 다 받아주다 보니 정작 본인 것을 뒤로 미루는 일이 잦습니다.',
			일: '사람과 돈이 오래 도는 일 — 관리·중개·요식·부동산·조직을 맡는 자리가 맞습니다.',
			대인: '중재를 잘합니다. 싸움 붙은 자리에 끼면 이상하게 정리가 됩니다. 부탁을 거절하는 연습이 필요합니다.'
		},
		금: {
			name: '금(金)', title: '쇠를 닮은 얼굴', tag: '끊고 맺는 상',
			기질: '단단한 기운입니다. 원칙이 서 있고, 아니라고 생각하면 아니라고 말합니다. ' +
				'맡은 일은 끝까지 갑니다. ' +
				'대신 한번 금이 가면 잘 안 붙습니다. 옳은 말을 차갑게 해서 손해 보는 일이 있습니다.',
			일: '기준을 세우고 지키는 일 — 법·회계·품질·기술·군경 쪽에서 힘을 씁니다.',
			대인: '넓게 사귀지 않지만 한번 맺으면 오래 갑니다. 말투를 한 번 더 다듬으면 적이 반으로 줍니다.'
		},
		수: {
			name: '수(水)', title: '물을 닮은 얼굴', tag: '스며드는 상',
			기질: '흐르는 기운입니다. 상황을 읽는 눈이 빠르고, 부딪히지 않고 돌아갑니다. ' +
				'머리가 잘 돌아서 남들이 며칠 걸릴 판단을 금방 합니다. ' +
				'다만 모양이 정해져 있지 않아서, 마음먹은 걸 끝까지 붙드는 힘은 약한 편입니다.',
			일: '판을 읽어야 하는 일 — 전략·투자·상담·창작처럼 정답이 없는 자리에서 빛납니다.',
			대인: '누구와도 무난하게 지냅니다. 그래서 정작 속을 터놓는 사람이 적습니다.'
		}
	};

	var 상생 = { 목: '수', 화: '목', 토: '화', 금: '토', 수: '금' };   // 나를 살려주는 오행
	var 상극 = { 목: '금', 화: '수', 토: '목', 금: '화', 수: '토' };   // 나를 치는 오행

	function score(f) {
		// 각 항목을 -1 ~ +1 로 바꾼다 (중앙값보다 크면 +)
		function z(v, mid, span) {
			var t = (v - mid) / span;
			return t < -1 ? -1 : t > 1 ? 1 : t;
		}
		var 길다 = z(f.ratio, MID.ratio, SPAN.ratio);
		var 이마넓다 = z(f.foreheadW, MID.foreheadW, SPAN.foreheadW);
		var 턱넓다 = z(f.jawW, MID.jawW, SPAN.jawW);
		var 턱뾰족 = -z(f.chinW, MID.chinW, SPAN.chinW);
		var 턱각짐 = -z(f.jawAngle, MID.jawAngle, SPAN.jawAngle);
		var 입술두껍다 = z(f.lipThick, MID.lipThick, SPAN.lipThick);

		return {
			목: 1.0 * 길다 + 0.5 * (-턱넓다) + 0.3 * (-턱각짐),
			화: 1.0 * 턱뾰족 + 0.7 * 이마넓다 + 0.3 * 길다,
			토: 1.0 * (-길다) + 0.8 * 턱넓다 + 0.3 * (-턱각짐),
			금: 1.0 * 턱각짐 + 0.5 * 턱넓다 + 0.3 * (-턱뾰족),
			수: 0.8 * (-턱각짐) + 0.7 * (-턱뾰족) + 0.5 * (-길다) + 0.4 * 입술두껍다
		};
	}

	/* 다섯 기운이 골고루 나오도록 잡아 주는 보정치.
	 * 얼굴 지표만으로 점수를 내면 '화'와 '금'에 몰린다 — 각진 턱과 뾰족한 턱이
	 * 실제 얼굴에서 흔하기 때문이다. 사진 80장으로 분포를 보며 맞춘 값이다.
	 * (관상이 원래 그렇다는 뜻이 아니라, 다섯 중 하나만 계속 나오면 재미가 없어서다) */
	var BIAS = { 목: 0.08, 화: -0.22, 토: 0.40, 금: -0.08, 수: 0.46 };

	function pct(s) {
		var ks = Object.keys(s), out = {}, sum = 0;
		ks.forEach(function (k) { s[k] += BIAS[k]; });
		ks.forEach(function (k) { out[k] = Math.exp(s[k] * 1.35); sum += out[k]; });
		ks.forEach(function (k) { out[k] = out[k] / sum * 100; });
		return out;
	}

	/* 삼정 — 셋 중 어디가 두드러지는가.
	 * ⚠ 고전 삼정은 '헤어라인~눈썹'을 상정으로 치는데, 랜드마크 10 은 헤어라인이 아니라
	 *   얼굴 윤곽의 꼭대기다. 그래서 1/3 씩으로 비교하면 늘 '상정이 짧다'가 나온다.
	 *   실측 중앙값(상 0.161 / 중 0.456 / 하 0.389)과 비교해 '남들보다 긴 쪽'을 고른다. */
	var 삼정중앙 = { up: 0.161, mid: 0.456, low: 0.389 };
	var 삼정폭 = { up: 0.016, mid: 0.037, low: 0.045 };
	function 삼정(f) {
		var d = {
			상정: (f.up - 삼정중앙.up) / 삼정폭.up,
			중정: (f.mid - 삼정중앙.mid) / 삼정폭.mid,
			하정: (f.low - 삼정중앙.low) / 삼정폭.low
		};
		var top = Object.keys(d).sort(function (a, b) { return d[b] - d[a]; })[0];
		var 균형 = Math.max(Math.abs(d.상정), Math.abs(d.중정), Math.abs(d.하정));
		if (균형 < 0.7) {
			return '이마·중안·하관의 길이가 서로 고릅니다. 관상에서 가장 좋게 보는 형태입니다. ' +
				'한 시기에 몰아서 크게 터지기보다, 초년·중년·말년이 고르게 굴러가는 흐름입니다. ' +
				'큰 굴곡이 없다는 건 심심하다는 뜻이 아니라, 무너져도 다시 세울 바닥이 있다는 뜻입니다.';
		}
		if (top === '상정') {
			return '이마(상정)가 깁니다. 초년운과 머리 쓰는 힘이 강한 형태입니다. ' +
				'어릴 때 배운 것, 초반에 만난 사람이 평생을 끌고 갑니다. ' +
				'대신 하관이 상대적으로 짧으면 말년에 쓸 것을 중년에 미리 쌓아 둬야 합니다.';
		}
		if (top === '중정') {
			return '눈썹에서 코끝까지(중정)가 깁니다. 30~50대에 힘이 실리는 형태입니다. ' +
				'자기 힘으로 자리를 만드는 시기가 인생의 한가운데에 옵니다. ' +
				'초년이 순탄치 않았더라도 중년에 뒤집는 흐름이 많습니다.';
		}
		return '코끝에서 턱까지(하정)가 깁니다. 뒤로 갈수록 좋아지는 형태입니다. ' +
			'젊을 때 고생한 것이 나중에 자리로 돌아옵니다. ' +
			'아랫사람·부하 복이 있어서, 나이 들수록 사람이 붙습니다.';
	}

	function 재물궁(f) {
		if (f.noseW > 0.312) {
			return '콧방울이 넉넉합니다. 관상에서 코는 재물이 담기는 그릇으로 봅니다. ' +
				'버는 힘보다 쥐고 있는 힘이 좋은 쪽입니다. 큰돈이 한 번에 들어오기보다 새는 데가 적습니다.';
		}
		if (f.noseW < 0.257) {
			return '콧방울이 야무지게 붙어 있습니다. 씀씀이가 깔끔하고 판단이 빠릅니다. ' +
				'다만 그릇이 좁다기보다 물이 빨리 도는 형태라, 들어온 돈을 어디에 묶어 둘지 정해 두는 게 좋습니다.';
		}
		return '코가 얼굴과 균형이 맞습니다. 벌이와 씀씀이가 크게 어긋나지 않는 형태입니다. ' +
			'큰 욕심을 내지 않으면 돈 때문에 크게 흔들릴 일은 적습니다.';
	}

	function 눈매(f) {
		if (f.eyeTilt > 0.125) return '눈꼬리가 올라가 있어 기가 강해 보입니다. 첫인상에서 만만치 않다는 인상을 줍니다.';
		if (f.eyeTilt < 0.031) return '눈꼬리가 내려가 있어 순해 보입니다. 사람들이 부탁을 많이 하는 얼굴입니다.';
		return '눈매가 반듯합니다. 감정을 크게 드러내지 않아 신뢰를 얻기 좋은 눈입니다.';
	}

	ReadUI.page({
		title: '얼굴로 보는 사주팔자',
		subtitle: '생년월일 말고, 얼굴로 보는 오행',
		note: '얼굴형을 목·화·토·금·수 다섯 기운으로 나누고, 이마·중안·하관의 비율(삼정)로 시기별 흐름을 봅니다.',
		button: '내 오행 보기',
		fileName: '얼굴사주',

		analyze: function (f) {
			var s = score(f), p = pct(s);
			var top = Object.keys(p).sort(function (a, b) { return p[b] - p[a]; })[0];
			var second = Object.keys(p).sort(function (a, b) { return p[b] - p[a]; })[1];
			var o = 오행[top], o2 = 오행[second];

			return {
				headline: o.name + ' ' + o.title,
				tagline: o.tag,
				bars: ['목', '화', '토', '금', '수'].map(function (k) {
					return { label: 오행[k].name, pct: p[k], on: k === top };
				}),
				sections: [
					{ h: '타고난 기질', p: o.기질 },
					{
						h: '섞여 있는 기운', p: '두 번째로 강한 것은 ' + o2.name + '입니다. ' +
							o.name + '의 성질에 ' + o2.name + '가 얹힌 형태라, ' + o2.tag +
							'의 면이 결정적인 순간에 나옵니다.'
					},
					{ h: '삼정 — 시기별 흐름', p: 삼정(f) },
					{ h: '재물궁 (코)', p: 재물궁(f) },
					{ h: '눈매', p: 눈매(f) },
					{ h: '맞는 일', p: o.일 },
					{ h: '사람 관계', p: o.대인 },
					{
						h: '어울리는 사람 · 조심할 사람',
						p: '나를 살려주는 기운은 ' + 오행[상생[top]].name + '입니다. ' +
							오행[상생[top]].tag + '을 가진 사람 옆에 있으면 일이 풀립니다. ' +
							'반대로 ' + 오행[상극[top]].name + '와는 부딪히기 쉽습니다. ' +
							'맞고 틀리고의 문제가 아니라 속도와 방식이 달라서 그렇습니다. 미리 알고 만나면 그만입니다.'
					}
				],
				share: '나는 ' + o.name + ' ' + o.title + ' — ' + o.tag
			};
		}
	});
})();
